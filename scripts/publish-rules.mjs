// Publishes the current rules to GitHub Pages (docs/ on main):
// validate → sign with the private key → verify against the shipped public key →
// write docs/<site>/rules.json(.sig) + the landing/privacy site → commit → push.
// A YouTube breakage is fixed by editing apps/<site>/rules/rules.json (bump
// "version") and running `npm run rules:publish`.
//
//   node scripts/publish-rules.mjs [site] [--no-push] [--no-commit]
//   RULES_PRIVATE_KEY_FILE=<path> overrides the key location (default .secrets/rules-private.jwk)
import { spawnSync } from "node:child_process";
import { readFile, writeFile, mkdir, cp, readdir } from "node:fs/promises";
import path from "node:path";
import { validateRules } from "../packages/engine/src/schema.js";
import { verifyRules } from "../packages/engine/src/signature.js";
import { signBytes } from "./rules-key.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const siteName = args.find((a) => !a.startsWith("--")) || "youtube";
const KEY_FILE = process.env.RULES_PRIVATE_KEY_FILE || path.join(ROOT, ".secrets", "rules-private.jwk");
const DOCS = path.join(ROOT, "docs");
const fail = (m) => {
  console.error(`✖ rules:publish: ${m}`);
  process.exit(1);
};
const git = (...a) => {
  const r = spawnSync("git", a, { cwd: ROOT, encoding: "utf8" });
  if (r.status !== 0) fail(`git ${a.join(" ")}: ${r.stderr.trim()}`);
  return r.stdout.trim();
};

const { default: site } = await import(new URL(`file:///${path.join(ROOT, "apps", siteName, "site.config.js").replace(/\\/g, "/")}`).href);

// Byte-exact LF text: the signature covers these exact bytes, and .gitattributes keeps docs/<site>/ un-normalised.
const text = (await readFile(path.join(ROOT, "apps", siteName, "rules", "rules.json"), "utf8")).replace(/\r\n/g, "\n");
let rules;
try {
  rules = JSON.parse(text);
} catch (e) {
  fail(`rules.json is not JSON: ${e.message}`);
}
const v = validateRules(rules, { site: site.id });
if (!v.ok) fail(`rules.json invalid:\n  ${v.errors.join("\n  ")}`);

const outDir = path.join(DOCS, siteName);
const outFile = path.join(outDir, "rules.json");
const prev = await readFile(outFile, "utf8").catch(() => null);
if (prev !== null && prev !== text && JSON.parse(prev).version === rules.version) {
  fail(`rules changed but "version" is still ${rules.version} — bump it, or installed copies will ignore the update`);
}

let privateJwk;
try {
  privateJwk = JSON.parse(await readFile(KEY_FILE, "utf8"));
} catch {
  fail(`no signing key at ${KEY_FILE} (restore it from your backup, or set RULES_PRIVATE_KEY_FILE)`);
}
const bytes = Buffer.from(text, "utf8");
const sig = await signBytes(privateJwk, bytes);
if (!(await verifyRules(site.rulesPublicKey, bytes, sig))) fail("signature does not verify against site.config.js rulesPublicKey — wrong private key?");

await mkdir(outDir, { recursive: true });
await writeFile(outFile, bytes);
await writeFile(`${outFile}.sig`, sig);

// Landing page + privacy policy (generated by `npm run store`) at the site root.
const siteSrc = path.join(ROOT, "store", "site");
for (const f of await readdir(siteSrc)) await cp(path.join(siteSrc, f), path.join(DOCS, f), { recursive: true });
await writeFile(path.join(DOCS, ".nojekyll"), ""); // serve files as-is, no Jekyll processing
console.log(`✔ signed rules ${rules.version} (${rules.rules.length} rules) → ${path.relative(ROOT, outFile)} (+ .sig)`);

if (args.includes("--no-commit")) process.exit(0);
git("add", "--", "docs", path.join("apps", siteName, "rules", "rules.json"));
if (spawnSync("git", ["diff", "--cached", "--quiet"], { cwd: ROOT }).status === 0) {
  console.log("  nothing changed — already published");
} else {
  git("commit", "-m", `Publish ${siteName} rules ${rules.version}`, "--", "docs", path.join("apps", siteName, "rules", "rules.json"));
  console.log(`  committed ${git("rev-parse", "--short", "HEAD")}`);
}
if (args.includes("--no-push")) process.exit(0);
git("push", "origin", "HEAD:main");
console.log(`  pushed — live within ~1 minute at ${site.rulesUrl}`);
console.log("  check: RULES_URL=… RULES_PUBLIC_KEY=… node scripts/check-remote-rules.mjs");
